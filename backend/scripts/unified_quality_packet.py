#!/usr/bin/env python3
"""Offline quality packet CLI. It never calls a model or approves a release."""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from app.domains.analysis import quality_packet as packet  # noqa: E402


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("build-draft", "validate", "evaluate-evidence", "make-blinded"))
    parser.add_argument("--packet", type=Path, default=ROOT / "evals/unified_credit_v1")
    parser.add_argument("--evidence", type=Path)
    parser.add_argument("--destination", type=Path)
    parser.add_argument("--report", type=Path)
    args = parser.parse_args()
    try:
        if args.command == "build-draft":
            packet.build_draft(args.packet)
            packet.write_templates(args.packet)
            result = packet.validate_packet(args.packet)
        elif args.command == "validate":
            result = packet.validate_packet(args.packet)
        elif args.command == "evaluate-evidence":
            if args.evidence is None:
                parser.error("--evidence is required; no provider output is generated by this tool")
            result = packet.evaluate_evidence(args.packet, args.evidence)
        else:
            if args.evidence is None or args.destination is None:
                parser.error("--evidence and a new --destination are required")
            result = packet.make_blinded(args.packet, args.evidence, args.destination)
        text = json.dumps(result, indent=2, ensure_ascii=False) + "\n"
        if args.report:
            args.report.write_text(text)
        print(text)
        if args.command == "evaluate-evidence":
            return 0 if result.get("evidence_complete") else 2
        return 0 if result.get("draft_inputs_valid", args.command == "make-blinded") else 2
    except (OSError, ValueError, KeyError, TypeError) as exc:
        print(json.dumps({"error": str(exc), "authorizes_release": False}), file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
